export function render({ state, shell, esc, icon, startTour, billingOn, openSupport }) {
  const topics = guideTopics({ billing: billingOn(), company: state.organizations.length > 0,
    owner: state.organizations.some(org => org.members.some(member => member.user_id === state.user.id && member.role === 'owner')) });
  let selected = topics.find(topic => topic.id === state.guideTopic) || topics[0];
  state.guideTopic = selected.id;
  const normalize = text => text.toLocaleLowerCase('ru-RU').replace(/ё/g, 'е');
  const haystack = topic => normalize([topic.title, topic.description, topic.intro, topic.note,
    ...(topic.steps || []).flat(), ...(topic.example || []), ...(topic.table?.rows || []).flat(), ...(topic.questions || []).flat()].join(' '));
  const results = query => topics.filter(topic => haystack(topic).includes(normalize(query.trim())));
  const link = topic => `#guide/${topic.id}`;

  shell('Гайд по кабинету', '<button type="button" class="button" id="guide-tour">Показать подсказки на экране</button>', `
    <div class="guide-layout">
      <section class="guide-directory" aria-label="Темы гайда">
        <search class="guide-search">${icon('search', 18)}<input type="search" id="guide-search" placeholder="Например, скриншот или доплата" aria-label="Поиск по гайду" value="${esc(state.guideQuery || '')}"></search>
        <div class="guide-search-status" id="guide-search-status" role="status" aria-live="polite"></div>
        <details class="guide-topics-disclosure" open><summary>Темы гайда ${icon('chevron', 16)}</summary><nav id="guide-topics" aria-label="Содержание гайда"></nav></details>
        <a class="guide-support" href="#chats">${icon('chat', 17)}<span>Нужна помощь?<strong>Написать в поддержку</strong></span>${icon('arrow', 16)}</a>
      </section>
      <div class="guide-reader" id="guide-reader"></div>
    </div>`, { kicker: 'Помощь в кабинете', lead: 'Пошаговые инструкции по заявкам, переписке, согласованию и настройкам.' });

  const directory = document.querySelector('#guide-topics');
  const reader = document.querySelector('#guide-reader');
  const search = document.querySelector('#guide-search');
  const disclosure = document.querySelector('.guide-topics-disclosure');
  if (window.matchMedia('(max-width: 800px)').matches) disclosure.open = false;
  function paint() {
    const matches = results(search.value);
    document.querySelector('#guide-search-status').textContent = search.value.trim() ? `Найдено тем: ${matches.length}` : `${topics.length} тем · выберите нужный шаг`;
    if (matches.length && !matches.includes(selected)) selected = matches[0];
    if (matches.length) {
      state.guideTopic = selected.id;
      if (location.hash !== link(selected)) history.replaceState(null, '', link(selected));
    }
    directory.innerHTML = matches.map(topic => `<a class="guide-topic ${topic === selected ? 'active' : ''}" href="${link(topic)}" ${topic === selected ? 'aria-current="page"' : ''}>${icon(topic.icon, 18)}<span><strong>${esc(topic.title)}</strong><small>${esc(topic.description)}</small></span>${icon('chevron', 14)}</a>`).join('');
    const active = directory.querySelector('[aria-current="page"]');
    if(active && disclosure.open) {
      const area = directory.getBoundingClientRect(), item = active.getBoundingClientRect();
      if(item.bottom > area.bottom) directory.scrollTop += item.bottom - area.bottom + 8;
      else if(item.top < area.top) directory.scrollTop -= area.top - item.top + 8;
    }
    if (!matches.length) {
      reader.innerHTML = `<section class="guide-empty"><span class="guide-article-icon">${icon('search', 26)}</span><h2>Ничего не найдено</h2><p>Попробуйте «создать заявку», «скриншот», «пароль» или другое слово.</p><button class="button" id="guide-clear">Показать все темы</button></section>`;
      document.querySelector('#guide-clear').onclick = () => { search.value = ''; state.guideQuery = ''; paint(); search.focus(); };
      return;
    }
    const index = topics.indexOf(selected);
    const current = matches.indexOf(selected);
    reader.innerHTML = `<article class="guide-article" aria-labelledby="guide-title">
      <div class="guide-article-meta"><span>${esc(selected.group)}</span><span>Тема ${index + 1} из ${topics.length}</span></div>
      <h2 id="guide-title" tabindex="-1">${esc(selected.title)}</h2><p class="guide-intro">${esc(selected.intro)}</p>
      ${selected.steps ? `<ol class="guide-steps">${selected.steps.map(([title, text]) => `<li><h3>${esc(title)}</h3><p>${esc(text)}</p></li>`).join('')}</ol>` : ''}
      ${selected.example ? `<section class="guide-example"><h3>${esc(selected.example[0])}</h3><p>${esc(selected.example[1])}</p></section>` : ''}
      ${selected.table ? `<div class="guide-table-wrap"><table class="guide-table"><thead><tr>${selected.table.headers.map(header => `<th scope="col">${esc(header)}</th>`).join('')}</tr></thead><tbody>${selected.table.rows.map(([name, text]) => `<tr><th scope="row">${esc(name)}</th><td>${esc(text)}</td></tr>`).join('')}</tbody></table></div>` : ''}
      ${selected.note ? `<p class="guide-note">${icon('alert', 17)}<span>${esc(selected.note)}</span></p>` : ''}
      ${selected.questions ? `<div class="guide-questions">${selected.questions.map(([question, answer]) => `<details><summary>${esc(question)}</summary><p>${esc(answer)}</p></details>`).join('')}</div>` : ''}
      ${selected.action ? `<a class="button primary guide-action" href="${esc(selected.action[0])}">${esc(selected.action[1])}${icon('arrow', 17)}</a>` : ''}
      <nav class="guide-pagination" aria-label="Переход между темами">${current > 0 ? `<a href="${link(matches[current - 1])}"><small>Предыдущая тема</small><strong>${esc(matches[current - 1].title)}</strong></a>` : '<span></span>'}${current + 1 < matches.length ? `<a href="${link(matches[current + 1])}"><small>Следующая тема</small><strong>${esc(matches[current + 1].title)} ${icon('arrow', 15)}</strong></a>` : '<span></span>'}</nav>
    </article>`;
  }
  search.addEventListener('input', () => { state.guideQuery = search.value; if(search.value.trim())disclosure.open = true; paint(); });
  document.querySelector('#guide-tour').onclick = startTour;
  document.querySelector('.guide-layout').addEventListener('click', event => {
    if(event.target.closest('a')?.getAttribute('href') === '#chats') { event.preventDefault(); openSupport(); }
  });
  directory.addEventListener('click', event => { if (event.target.closest('a')) state.guideFocus = true; });
  reader.addEventListener('click', event => { if (event.target.closest('.guide-pagination a')) state.guideFocus = true; });
  paint();
  if (state.guideFocus) {
    state.guideFocus = false;
    document.querySelector('#guide-title')?.focus({ preventScroll: true });
    document.querySelector('#guide-title')?.scrollIntoView({ block: 'start', behavior: 'instant' });
  }
}
